// PlainSlang data access — dual-runtime.
//
//  Runtime A (Node: local dev, Docker) ─ uses `pg` over DATABASE_URL.
//  Runtime B (Cloudflare Workers via OpenNext) ─ uses Supabase's HTTP API
//    (supabase-js) with the service-role key; no TCP sockets, no LISTEN.
//
//  Realtime:
//    Node runtime  → SSE (/api/stream) fed by pg LISTEN/NOTIFY (lib/db.js).
//    Edge runtime  → browsers subscribe DIRECTLY to Supabase Realtime over
//    WebSockets (lib/useLive.js picks the transport automatically).
//
//  Which mode is active is decided once per process:
//    SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY set  → supabase mode
//    else DATABASE_URL                             → pg mode

import { createClient } from '@supabase/supabase-js';

export const MODE =
  process.env.SUPABASE_URL && process.env.SUPABASE_SERVICE_ROLE_KEY
    ? 'supabase'
    : process.env.DATABASE_URL
      ? 'pg'
      : 'static'; // no DB configured: serve the committed site/data.json read-only

const g = globalThis.__plainslangData || (globalThis.__plainslangData = {});

export function getSupabase() {
  if (!g.supabase) {
    g.supabase = createClient(
      process.env.SUPABASE_URL,
      process.env.SUPABASE_SERVICE_ROLE_KEY,
      { auth: { persistSession: false }, realtime: { params: {} } }
    );
  }
  return g.supabase;
}

// ---------------------------------------------------------------------------
// STATIC read-only mode: no DATABASE_URL and no Supabase vars. Loads the
// committed site/data.json (the static edition's daily-verified snapshot) and
// serves all reads from memory. Writes are rejected with READ_ONLY so the
// deployment still works with zero configuration.
// ---------------------------------------------------------------------------
import staticData from '../site/data.json';

function loadStaticStore() {
  if (g.staticStore) return g.staticStore;
  // Bundled at build time (works on Node AND Cloudflare Workers, where there
  // is no filesystem). site/data.json is regenerated by the daily GitHub
  // Action, and every push triggers a redeploy, so the bundle stays fresh.
  const d = staticData;
  const rows = d.terms.map((t) => ({
    id: t.id, term: t.term, emoji: t.emoji, definition: t.definition,
    example: t.example, notes: t.notes, age_group: t.ageGroup,
    difficulty: t.difficulty, say: t.say, source_name: t.sourceName,
    source_url: t.sourceUrl, tags: JSON.stringify(t.tags || []),
    is_woty: t.isWoty ? 1 : 0, trending: t.trending ? 1 : 0,
    trending_evidence: t.trendingEvidence ? JSON.stringify(t.trendingEvidence) : null,
    is_seed: t.isSeed === false ? 0 : 1, category: t.category || 'teen',
    related: JSON.stringify(t.related || []),
    created_at: d.generatedAt, updated_at: d.generatedAt,
  }));
  const meta = new Map();
  if (d.trendingSnapshot) meta.set('trending_status', JSON.stringify(d.trendingSnapshot));
  if (d.radarSnapshot) meta.set('radar_status', JSON.stringify(d.radarSnapshot));
  g.staticStore = { rows, meta, generatedAt: d.generatedAt };
  return g.staticStore;
}

function readOnlyError() {
  const e = new Error('This deployment is read-only (no database configured). Terms are managed in the repo.');
  e.code = 'READ_ONLY';
  return e;
}

// ---------------------------------------------------------------------------
// Row helpers (shared shape both modes return: snake_case DB rows)
// ---------------------------------------------------------------------------

export function rowToTerm(r) {
  return {
    id: r.id,
    term: r.term,
    emoji: r.emoji,
    definition: r.definition,
    example: r.example,
    notes: r.notes,
    ageGroup: r.age_group,
    difficulty: r.difficulty,
    say: r.say,
    sourceName: r.source_name,
    sourceUrl: r.source_url,
    tags: safeJson(r.tags, []),
    isWoty: !!r.is_woty,
    trending: !!r.trending,
    trendingEvidence: safeJson(r.trending_evidence, null),
    isSeed: !!r.is_seed,
    category: r.category || 'teen',
    related: safeJson(r.related, []),
    createdAt: r.created_at,
    updatedAt: r.updated_at,
  };
}

export function termToRow(clean, { isSeed = 0, now }) {
  return {
    term: clean.term,
    emoji: clean.emoji || '',
    definition: clean.definition,
    example: clean.example || null,
    notes: clean.notes || null,
    age_group: clean.ageGroup || 'gen_z',
    difficulty: clean.difficulty || 'medium',
    say: clean.say || null,
    source_name: clean.sourceName || null,
    source_url: clean.sourceUrl || null,
    tags: JSON.stringify(clean.tags || []),
    is_woty: 0,
    trending: 0,
    is_seed: isSeed,
    category: clean.category || 'teen',
    related: '[]',
    created_at: now,
    updated_at: now,
  };
}

function safeJson(s, fallback) {
  if (!s) return fallback;
  if (typeof s === 'object') return s; // PostgREST may return parsed jsonb
  try {
    return JSON.parse(s);
  } catch {
    return fallback;
  }
}

